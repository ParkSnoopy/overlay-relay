#!/usr/bin/env python3
"""Synchronize generated client/server wire versions from server/Cargo.toml."""

import argparse
from pathlib import Path
import re
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def outputs(root: Path) -> tuple[str, dict[Path, str]]:
    manifest = tomllib.loads((root / "server/Cargo.toml").read_text())
    version = manifest["package"]["version"]
    match = re.fullmatch(r"(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?", version)
    if not match:
        raise ValueError("server version must be a semantic version")
    major, minor, _ = map(int, match.groups())
    wire = major or minor
    if not 0 < wire <= 0x7FFFFFFF:
        raise ValueError("protocol generation must be positive and fit a signed 32-bit integer")
    go = f'''// Code generated by scripts/bump_version.py --sync; DO NOT EDIT.
package overlay

// ReleaseVersion is inherited from server/Cargo.toml.
const ReleaseVersion = "{version}"

// Version is the compatibility generation: minor before 1.0, major thereafter.
const Version = {wire}

// AuthDomain binds authentication to the wire generation.
const AuthDomain = "overlay-relay/auth/v{wire}:"
'''
    rust = f'''// Code generated by scripts/bump_version.py --sync; DO NOT EDIT.

/// The compatibility generation: minor before 1.0, major thereafter.
pub const VERSION: u32 = {wire};

/// Domain separator for authenticated handshakes.
pub const AUTH_DOMAIN: &str = "overlay-relay/auth/v{wire}:";

/// Release that generated these protocol constants.
pub const RELEASE_VERSION: &str = "{version}";
'''
    return version, {root / "client/overlay/version.go": go, root / "server/src/version.rs": rust}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--sync", action="store_true", help="copy the server version into generated client/server metadata")
    mode.add_argument("--check", action="store_true", help="check release and protocol metadata without writing")
    args = parser.parse_args()
    try:
        version, expected = outputs(ROOT)
        stale = []
        for path, content in expected.items():
            if path.exists() and path.read_text() == content:
                continue
            if args.sync:
                path.write_text(content)
            else:
                stale.append(str(path.relative_to(ROOT)))
        if stale:
            print("version mismatch: " + ", ".join(stale) + "; run --sync", file=sys.stderr)
            return 1
        print(f"overlay-relay {version}: server/client release and protocol versions match")
        return 0
    except (OSError, ValueError, KeyError, StopIteration) as error:
        print(f"version check failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
